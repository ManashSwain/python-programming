cars = ["Audi", "BMW", "Benz"]

for i in cars:
    print(i)

# output

# Audi
# BMW
# Benz

# Iterating individual strings in list

for car in cars:
    for i in car:
        print(i)

# Output 
# A
# u
# d
# i
# B
# M
# W
# B
# e
# n
